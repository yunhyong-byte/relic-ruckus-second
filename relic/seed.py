ORIGINAL_IMAGE = Credit(
    "Relic Ruckus original illustration", "Relic Ruckus project",
    "Original artwork generated for Relic Ruckus", "Relic Ruckus original illustration",
)


def seed_cards():
    for category, gallery in zip(CATEGORIES, GALLERIES):
        for card_id, name, _, heritage, bio, alt, scores in gallery:
            subject, reference = REFERENCES[card_id]
            portrait = ART / f"{card_id}.webp"
            image = portrait.read_bytes() if portrait.is_file() else None
            yield Card(
                card_id, name, subject, category, heritage, bio, scores, alt,
                image=image, mime="image/webp" if image else None,
                image_credit=ORIGINAL_IMAGE if image else Credit(),
                mode=MODES[0] if image else MODES[2],
                reference=reference,
            )
